const ST = (name, muscles, perSide = false) => ({ name, type: 'stretch', category: 'Stretch', muscles, perSide });
const I = (name, modality) => ({ name, type: 'interval', category: 'Cardio', muscles: ['Cardio'], modality });
const Z = (name, modality) => ({ name, type: 'steady', category: 'Cardio', muscles: ['Cardio'], modality });
// Gym exercises logged as reps with optional added/assisted load (bands, hyperextensions, etc.).
const W = (name, muscles, perSide = false) => ({ name, type: 'bodyweight', category: 'Strength', muscles, perSide });
// Mobility drills counted in reps.
const M = (name, muscles, perSide = false) => ({ name, type: 'bodyweight', category: 'Stretch', muscles, perSide });
// Rehab isometrics: timed holds.
const R = (name, muscles, perSide = false) => ({ name, type: 'hold', category: 'Rehab', muscles, perSide });
const since = (v, list) => list.map(e => ({ ...e, since: v }));

